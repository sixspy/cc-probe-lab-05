"""甲（甲形态：切流账册按观测时排序后物化，单轨）。

失败测甲：同站两笔逆序到达后，现行入栏缓冲首条仍是较晚观测则红。
夹具：乱序两笔（现行首条须较早）+ 正序对照 + 观测序裁决只读接口。
"""
from __future__ import annotations

from app.db import 连接
from app.services import 装载, 目录


def _报文(编号: str, 观测时: str, 读数: float = 31.0) -> dict:
    return {
        "报文编号": 编号,
        "站点键": "站-河东",
        "指标键": "PM25",
        "读数": 读数,
        "观测时": 观测时,
    }


def _同站在栏观测序() -> list[dict]:
    conn = 连接()
    try:
        return [
            dict(r)
            for r in conn.execute(
                "SELECT * FROM 入栏缓冲 WHERE 站点键=? AND 命运='在栏' ORDER BY 观测序",
                ("站-河东",),
            ).fetchall()
        ]
    finally:
        conn.close()


def test_逆序灌入栏后现行首条观测时须较早():
    # 先到的观测时更晚（08:40），后到的观测时更早（08:10）
    装载.装一批({"批次编号": "乱-甲-1", "报文": [_报文("J-late", "2026-11-24T08:40:00Z", 40.0)]})
    装载.装一批({"批次编号": "乱-甲-2", "报文": [_报文("J-early", "2026-11-24T08:10:00Z", 20.0)]})

    行 = _同站在栏观测序()
    assert len(行) == 2
    # 现行（物理落库序/观测序=0）首条须是观测时更早那笔，而不是先灌入的较晚笔
    assert 行[0]["报文编号"] == "J-early"
    assert 行[0]["观测时"] == "2026-11-24T08:10:00Z"
    assert 行[0]["观测序"] == 0
    assert 行[1]["报文编号"] == "J-late"
    assert 行[1]["观测序"] == 1
    # 收到序仍保留：先到的较晚笔到达序更小，两序可分开看
    assert 行[1]["到达序"] < 行[0]["到达序"]


def test_正序对照不改变观测序():
    装载.装一批({"批次编号": "顺-甲", "报文": [
        _报文("S-early", "2026-11-24T09:00:00Z", 20.0),
        _报文("S-late", "2026-11-24T09:30:00Z", 40.0),
    ]})
    行 = _同站在栏观测序()
    assert [r["报文编号"] for r in 行] == ["S-early", "S-late"]
    assert [r["观测序"] for r in 行] == [0, 1]


def test_观测序裁决只读接口字段与形态标记():
    from app.services import 观测序

    装载.装一批({"批次编号": "裁-1", "报文": [_报文("V-late", "2026-11-24T10:20:00Z", 40.0)]})
    装载.装一批({"批次编号": "裁-2", "报文": [_报文("V-early", "2026-11-24T10:05:00Z", 20.0)]})

    裁决 = 观测序.裁决()
    本站 = [r for r in 裁决 if r["站点键"] == "站-河东" and r["指标键"] == "PM25"]
    assert 本站, "裁决接口须按站点输出观测序裁决"
    r = 本站[0]
    # 题面字段：站点键、首观测时、形态标记
    assert set(["站点键", "首观测时", "形态标记"]).issubset(r.keys())
    assert r["首观测时"] == "2026-11-24T10:05:00Z"
    # 单轨甲形态：缓冲序即观测时序；发生过逆序到达 → 须标乱序重排
    assert r["形态标记"] == "乱序重排"

    # 正序对照形态
    装载.装一批({"批次编号": "裁-顺", "报文": [
        {
            "报文编号": "V2-a", "站点键": "站-北岭", "指标键": "PM25",
            "读数": 18.0, "观测时": "2026-11-24T11:00:00Z",
        },
        {
            "报文编号": "V2-b", "站点键": "站-北岭", "指标键": "PM25",
            "读数": 19.0, "观测时": "2026-11-24T11:10:00Z",
        },
    ]})
    北岭 = [r for r in 观测序.裁决() if r["站点键"] == "站-北岭"][0]
    assert 北岭["形态标记"] == "正序"
    assert 北岭["首观测时"] == "2026-11-24T11:00:00Z"


def test_目录缓冲页按观测序返回():
    装载.装一批({"批次编号": "页-1", "报文": [_报文("P-late", "2026-11-24T12:40:00Z", 40.0)]})
    装载.装一批({"批次编号": "页-2", "报文": [_报文("P-early", "2026-11-24T12:10:00Z", 20.0)]})
    rows = [r for r in 目录.缓冲列表() if r["站点键"] == "站-河东"]
    assert [r["报文编号"] for r in rows[:2]] == ["P-early", "P-late"]
    # 页面行须带观测序/到达序，两序可分开看
    assert rows[0]["观测序"] == 0 and rows[0]["到达序"] > rows[1]["到达序"]
